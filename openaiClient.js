// OpenAI 共通呼び出し
// ══════════════════════════════════════════════════════════════
async function callOpenAI(systemPrompt, userMessage, history = [], options = {}) {
  if (!OPENAI_API_KEY || !costTracker.canProcess()) return null;
  try {
    const historyMessages = (history || []).map(({ role, content }) => ({ role, content }));
    const body = {
      model: OPENAI_MODEL,
      input: [
        { role: 'system', content: systemPrompt },
        ...historyMessages,
        { role: 'user', content: userMessage },
      ],
      temperature: 0.7,
    };
    if (options.max_output_tokens) body.max_output_tokens = options.max_output_tokens;
    // Structured Outputs（Responses API text.format:{type:'json_schema',strict:true}）。
    //   options.structuredOutput = { name, schema } を渡した呼び出しのみ有効化する任意経路。
    //   未指定時は従来どおりの自由記述のまま（他のcallOpenAI()呼び出しへは一切影響しない）。
    if (options.structuredOutput && options.structuredOutput.schema) {
      body.text = {
        format: {
          type: 'json_schema',
          name: options.structuredOutput.name || 'structured_output',
          schema: options.structuredOutput.schema,
          strict: true,
        },
      };
    }
    const response = await axios.post(
      OPENAI_API_URL,
      body,
      {
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${OPENAI_API_KEY}`,
        },
      }
    );
    const outputText = response?.data?.output_text || response?.data?.output?.[0]?.content?.[0]?.text || '';
    const usage = response?.data?.usage || {};
    const inputTokens  = usage.input_tokens  || usage.inputTokens  || 0;
    const outputTokens = usage.output_tokens || usage.outputTokens || 0;
    if (inputTokens || outputTokens) {
      addOpenAIUsage(OPENAI_MODEL, inputTokens, outputTokens, 'aiDevelopment', 'text');
      // A-2-5: 既存料金記録に加え、Supabase へ料金イベントを保存（dual-write）。
      //   保存失敗しても AI回答は返す（persistOpenAICostEvent は throw しない）。
      await persistOpenAICostEvent({
        responseId:  response?.data?.id,
        model:       OPENAI_MODEL,
        inputTokens,
        outputTokens,
        assignee:    'aiDevelopment',
        usageType:   'text',
      });
    }
    return outputText || null;
  } catch (error) {
    console.error('OpenAI request failed:', error.response?.data || error.message);
    return null;
  }
}

