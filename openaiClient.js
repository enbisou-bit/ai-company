// Phase39: 回答テキストに不確かさシグナルがあるか判定
function _hasUncertaintySignal(text) {
  const signals = [
    '要確認', '不明', '調査が必要', '確認が必要', '要調査', '不足', 'わかりません', '分かりません',
    'not sure', 'unclear', 'uncertain', 'need to verify', '検討が必要', '詳細不明',
  ];
  return signals.some(function(s) { return text.includes(s); });
}

